"""Writes the plugin's model files models/v2_<ball>.txt from balls.PARTS (so the game shows what the previews show).

  python write_models.py

Each part becomes `material <part> asset /Game/Mods/elemental_balls/<instance>` plus its mesh (make_meshes.py's
v2_<mesh>.glb, which all share one ±50 cm bounding box, so `at=0,0,-50` centres them on the ball; the aura is the
plugin's 1 m sphere.glb scaled to AuraScale). `set` lines carry the values races multiply (balls.RACE).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import balls  # noqa: E402

MODELS = os.path.normpath(os.path.join(HERE, "..", "..", "models"))
BASE = "/Game/Mods/elemental_balls"


def main():
    for ball, parts in balls.ALL.items():
        lines = ["# %s (Elemental Balls v2). GENERATED by unreal/Scripts/write_models.py from balls.py: edit those, not this." % ball,
                 "# Real UE 5.8 materials cooked into assets/ and script-made meshes (unreal/Scripts/make_meshes.py).",
                 "ball hidden"]
        race = []
        for mesh, mi, master, ov in parts:
            name = mesh
            lines.append("material %s asset %s/%s.%s" % (name, BASE, mi, mi))
            for k, factor in balls.RACE[master].items():
                if k in ov:
                    lines.append('set %s "%s" %g' % (name, k, ov[k]))
                    race.append('race %s "%s" %g' % (name, k, factor))
            if mesh == "ball":
                lines.append("mesh sphere.glb size=98 at=0,0,-49 material=%s" % name)
            elif mesh == "aura":
                d = 100.0 * balls.AURA_SCALE * 0.98
                lines.append('set %s "ShellRadius" %g' % (name, d / 2))
                lines.append("mesh sphere.glb size=%g at=0,0,%g material=%s" % (d, -d / 2, name))
            else:
                lines.append("mesh v2_%s.glb at=0,0,-50 material=%s" % (mesh, name))
        lines.append("# races are in daylight: brighter inside and a stronger aura on the race ball only")
        lines += race
        with open(os.path.join(MODELS, "v2_%s.txt" % ball.lower()), "w") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote models/v2_%s.txt" % ball.lower())


if __name__ == "__main__":
    main()
